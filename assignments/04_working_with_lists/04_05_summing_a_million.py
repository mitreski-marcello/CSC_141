# Create a list of numbers from 1 to one million
numbers = list(range(1, 1000001))

# Use min() to check the smallest number
print(f"Minimum: {min(numbers)}")

# Use max() to check the largest number
print(f"Maximum: {max(numbers)}")

# Use sum() to add all the numbers
total = sum(numbers)
print(f"Sum: {total}")