#PEP 8 is Python's official style guide for coding conventions, authored by Guido van Rossum, Barry Warsaw, and Alyssa Coghlan. The core philosophy behind PEP 8 is 
# that code is read far more often than it is written, making readability and consistency paramount.

#The guide covers code layout, indentation, and naming conventions, emphasizing that consistency within a project is more important than adhering 
# strictly to the style guide when it would reduce readability. Key recommendations include using 4 spaces for indentation 
# (not tabs), limiting lines to 79 characters, naming functions and variables in lowercase with underscores (snake_case), and using CapWords for class names.

#While not mandatory, PEP 8 remains the primary style reference for the Python community and helps create alignment around what "Pythonic" code looks like. 
# Many professional developers and organizations enforce PEP 8 using automated tools like linters and formatters to ensure consistency across codebases and 
# make code easier to maintain and collaborate on.